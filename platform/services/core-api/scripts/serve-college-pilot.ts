import { readFile, realpath } from "node:fs/promises";
import { dirname, isAbsolute, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { loadCollegeAttendanceReview } from "../lib/chapter11/college-attendance-review";
import { createCollegeAttendanceServer } from "../lib/chapter11/college-attendance-server";
import { CollegePilot } from "../lib/chapter11/college-pilot-store";
import { localReadinessComposer } from "../lib/chapter11/college-pilot-engine";
import { verifyPrivateOriginals } from "../lib/chapter11/college-pilot-sources";

process.umask(0o077);
const here = dirname(fileURLToPath(import.meta.url)), input = process.argv[2];
if (!input) throw new Error("Pass the private attendance.json file");
const root = await realpath(resolve(here, "../../../../runtime/college-attendance")), folder = await realpath(dirname(input));
const location = relative(root, folder);
if (location.startsWith("..") || isAbsolute(location)) throw new Error("Private sources must stay inside runtime/college-attendance");
const port = Number(process.argv[3] ?? 3503);
if (!Number.isInteger(port) || port < 1024 || port > 65535) throw new Error("Choose a local port between 1024 and 65535");
const review = await loadCollegeAttendanceReview(root, input);
await verifyPrivateOriginals(root, folder, review);
const pilot = new CollegePilot(folder, review, localReadinessComposer());
const assets = resolve(here, "../local/college-attendance");
const [html, script, css] = await Promise.all(["index.html", "review.js", "review.css"].map(name => readFile(resolve(assets, name), "utf8")));
const server = createCollegeAttendanceServer(review, { html: html!, script: script!, css: css! }, pilot);
server.on("error", () => { console.error("Could not start private pilot; check the port."); pilot.close(); process.exitCode = 1; });
server.listen(port, "127.0.0.1", () => { console.log(`Private college workflow: http://127.0.0.1:${port}`); console.log(`${review.students.length} students. Model: ${pilot.composer?.modelId ?? "unconfigured; labelled deterministic mode"}. Student risk and publication remain blocked.`); });
for (const signal of ["SIGINT", "SIGTERM"] as const) process.on(signal, () => { server.close(() => pilot.close()); });
