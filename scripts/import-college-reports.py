#!/usr/bin/env python3
"""Import unique Full_Attendance and CIE_ATTENDANCE XLS sources locally.

Use the existing independently verified reader. Preserve raw CIE, attendance,
eligibility and course legend cells without deriving risk, GPA or absences.
"""
import argparse
from collections import Counter
from datetime import datetime, timezone
import importlib.util
import json
import math
import os
from pathlib import Path
import re
import shutil
import uuid

spec = importlib.util.spec_from_file_location("attendance_import", Path(__file__).with_name("import-college-attendance.py"))
attendance = importlib.util.module_from_spec(spec)
spec.loader.exec_module(attendance)
FIELDS = {"CIE", "CIE Theory", "CIE Lab", "Attendance", "Attendance Theory", "Attendance Lab", "Eligible/not eligible"}


def classify_cie(value, field):
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        if not math.isfinite(value) or value < 0 or (field.startswith("Attendance") and value > 100):
            raise ValueError("Invalid CIE/attendance numeric value")
        if field == "Eligible/not eligible":
            raise ValueError("Eligibility must retain its source token")
        return "number"
    if isinstance(value, str) and value in ("", "-"):
        return "blank" if value == "" else "source_status"
    if field == "Eligible/not eligible" and value in ("Yes", "No"):
        return "source_status"
    raise ValueError("Unknown CIE source token; inspect the source before importing")


def parse_cie(path, identities):
    book, recovery, verified = attendance.read_verified(path)
    if book.nsheets != 1:
        raise ValueError("Expected one CIE sheet")
    sheet = book.sheet_by_index(0)
    if sheet.name != "CIE_ATTENDANCE" or sheet.nrows < 9 or sheet.ncols < 6:
        raise ValueError("Unsupported CIE report layout")
    if attendance.text(sheet.cell_value(2, 0)) != "FINAL CIE & ATTENDANCE REPORT":
        raise ValueError("CIE report title changed")
    scope = re.fullmatch(r"(.+)-Semester\s*:\s*(\d+)\s*-SEC\s+([A-Z0-9]+)", attendance.text(sheet.cell_value(3, 0)))
    if not scope or [attendance.text(v) for v in sheet.row_values(5)[:3]] != ["SL. No.", "Student Name", "USN"]:
        raise ValueError("CIE scope or identity headers changed")
    legend_rows = [r for r in range(7, sheet.nrows) if [attendance.text(v) for v in sheet.row_values(r)[:4]] == ["Sl.No", "Subject Code", "Subject Name", "Credit"]]
    if len(legend_rows) != 1:
        raise ValueError("Expected one explicit course legend")
    legend_start = legend_rows[0]
    columns, course, seen = [], None, set()
    for col in range(3, sheet.ncols):
        label = attendance.text(sheet.cell_value(5, col))
        if label:
            if label in seen:
                raise ValueError("Duplicate CIE course header")
            course = label; seen.add(label)
        field = attendance.text(sheet.cell_value(6, col))
        if not course or field not in FIELDS or (course, field) in {(c['course'], c['field']) for c in columns}:
            raise ValueError("Unknown or duplicate CIE field header")
        columns.append({"column": col, "course": course, "field": field})
    legend, footer = [], []
    for r in range(legend_start + 1, sheet.nrows):
        values = sheet.row_values(r)
        if not any(v != "" for v in values):
            continue
        if isinstance(values[0], (int, float)):
            code, name, credits = attendance.text(values[1]), attendance.text(values[2]), values[3]
            if code not in seen or not name or not isinstance(credits, (int, float)) or not math.isfinite(credits) or credits <= 0 or any(v != "" for v in values[4:]):
                raise ValueError("Invalid course legend")
            legend.append({"course": code, "title": name, "credits": credits, "sourceRow": r + 1})
        elif isinstance(values[0], str) and values[0].startswith("Report Generated By:") and not any(v != "" for v in values[1:]):
            footer.append({"value": values[0], "sourceCell": f"A{r+1}"})
        else:
            raise ValueError("Unrecognized CIE footer row")
    if len(legend) != len(seen) or {c['course'] for c in legend} != seen:
        raise ValueError("Course legend does not match all course groups")
    source_id = attendance.checksum(path.read_bytes())
    rows, seen_ids = [], set()
    for r in range(7, legend_start):
        values = sheet.row_values(r)
        if not any(v != "" for v in values):
            continue
        serial, name, srn = values[0], attendance.text(values[1]), attendance.text(values[2]).upper()
        if not isinstance(serial, (int, float)) or not math.isfinite(serial) or serial != len(rows)+1 or not name or not re.fullmatch(r"[A-Z0-9]{5,40}", srn) or srn in seen_ids:
            raise ValueError(f"Invalid or duplicated CIE identity at row {r+1}")
        seen_ids.add(srn)
        if srn not in identities:
            identities[srn] = {"studentId": str(uuid.uuid4()), "displayId": f"Student {len(identities)+1:03d}"}
        cells = [{"course": c['course'], "field": c['field'], "sourceCell": f"{attendance.xlrd.formula.colname(c['column'])}{r+1}",
                  "rawValue": values[c['column']], "kind": classify_cie(values[c['column']], c['field'])} for c in columns]
        rows.append({**identities[srn], "srn": srn, "studentName": name, "sourceRow": r+1, "cells": cells})
    return {"schemaVersion": "aura.college-cie.v1", "source": {"id": source_id, "filename": path.name, "sheet": sheet.name,
        "institution": attendance.text(sheet.cell_value(1, 0)), "department": scope[1], "semester": int(scope[2]),
        "section": f"Section {scope[3]}", "periodStart": None, "periodEnd": None, "academicTerm": None,
        "independentReadersAgree": True, "verifiedCells": verified, "parserRecoveryRequired": recovery,
        "columns": columns, "legend": legend, "footer": footer}, "rows": rows,
        "summary": {"studentRows": len(rows), "recordedCells": sum(len(r['cells']) for r in rows),
                    "kinds": dict(Counter(c['kind'] for r in rows for c in r['cells']))}}


def compare_attendance(bundle, cie):
    """Compare like-labelled raw numbers only; dates and units remain unknown."""
    lookup = {(o['studentId'], o['semester'], o['section'], o['courseKey']): o for o in bundle['observations']}
    counts, differences = Counter(), []
    for row in cie['rows']:
        for cell in row['cells']:
            if cell['field'] != 'Attendance':
                continue
            other = lookup.get((row['studentId'], cie['source']['semester'], cie['source']['section'], cell['course'].upper()))
            if not other:
                counts['noMatchingCourse'] += 1
            elif cell['kind'] != 'number' or other['kind'] != 'number':
                counts['statusOrMissingNotComparable'] += 1
            elif cell['rawValue'] == other['rawValue']:
                counts['equalNumericSourceValues'] += 1
            else:
                counts['differentNumericSourceValues'] += 1
                differences.append({'studentId': row['studentId'], 'course': cell['course'],
                    'fullAttendanceValue': other['rawValue'], 'cieAttendanceValue': cell['rawValue'],
                    'fullSourceId': other['sourceId'], 'cieSourceId': cie['source']['id'],
                    'fullSourceCell': other['sourceCell'], 'cieSourceCell': cell['sourceCell']})
    return {'counts': dict(counts), 'differences': differences, 'periodsConfirmed': False, 'sourcesMerged': False}


def import_reports(downloads, output, previous=None):
    private_root = (attendance.PROJECT / "runtime/college-attendance").resolve()
    output = output.resolve()
    if private_root not in output.parents:
        raise ValueError("Use a dated import folder under runtime/college-attendance")
    paths = sorted(p for p in downloads.iterdir() if p.is_file() and p.suffix.lower() == ".xls" and re.search("attendance", p.name, re.I))
    if not paths:
        raise ValueError("No attendance XLS reports found")
    unique, aliases = {}, []
    for path in paths:
        fingerprint = attendance.checksum(path.read_bytes())
        aliases.append({"filename": path.name, "sha256": fingerprint})
        unique.setdefault(fingerprint, path)
    full, cies = [], []
    for path in unique.values():
        book, _, _ = attendance.read_verified(path)
        if book.sheet_names() == ["Full_Attendance"]:
            full.append(path)
        elif book.sheet_names() == ["CIE_ATTENDANCE"]:
            cies.append(path)
        else:
            raise ValueError(f"Unrecognized attendance workbook: {path.name}")
    if not full or len(cies) != 1:
        raise ValueError("Expected Full_Attendance reports and one unique final CIE report")
    output.mkdir(parents=True, exist_ok=True, mode=0o700); output.chmod(0o700)
    identity_path = output / "private-identity-map.json"
    if previous and not identity_path.exists():
        previous = previous.resolve()
        if private_root not in previous.parents:
            raise ValueError("Previous identity map must be in the private import directory")
        attendance.write_private(identity_path, json.loads((previous / "private-identity-map.json").read_text()))
    identities = json.loads(identity_path.read_text()) if identity_path.exists() else {}
    # Validate every source before the existing importer writes any derived records.
    for path in full:
        attendance.parse_report(path, identities)
    cie = parse_cie(cies[0], identities)
    attendance.write_private(identity_path, identities)
    summary = attendance.ingest(full, output)
    attendance.write_private(output / "cie.json", cie)
    dest = output / "originals" / f"{cie['source']['id'][:16]}-{cies[0].name}"
    if dest.exists() and attendance.checksum(dest.read_bytes()) != cie['source']['id']:
        raise ValueError("Preserved CIE original has changed")
    if not dest.exists():
        shutil.copyfile(cies[0], dest); dest.chmod(0o600)
    bundle = json.loads((output / "attendance.json").read_text())
    combined_id = attendance.checksum("\n".join(sorted(unique)).encode())
    full_students = {r['studentId'] for r in bundle['enrollments']}
    report = {"schemaVersion": "aura.college-import-inventory.v1", "datasetId": combined_id,
        "attendanceDatasetId": bundle['datasetId'], "importedAt": datetime.now(timezone.utc).isoformat(),
        "filesFound": len(paths), "uniqueFiles": len(unique), "duplicateCopies": len(paths)-len(unique),
        "aliases": aliases, "attendance": summary, "cie": cie['summary'],
        "cieStudentsMatchedByExactId": sum(r['studentId'] in full_students for r in cie['rows']),
        "combinedUniqueStudents": len(full_students | {r['studentId'] for r in cie['rows']}),
        "cieNumericFields": dict(Counter(c['field'] for r in cie['rows'] for c in r['cells'] if c['kind'] == 'number')),
        "rawAttendanceComparison": compare_attendance(bundle, cie),
        "fullAgentReviewReady": False, "databaseWritten": False,
        "unknowns": ["academic year and reporting dates", "attendance units, zero, NA, TNS and dash meanings", "CIE maximum marks and grade rules", "mentor mapping", "LMS activity", "career evidence or confirmed non-applicability"]}
    attendance.write_private(output / "download-inventory.json", report)
    return report


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("downloads", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--previous", type=Path)
    args = parser.parse_args(); os.umask(0o077)
    result = import_reports(args.downloads, args.output, args.previous)
    print(json.dumps({k: v for k, v in result.items() if k not in ("aliases",)}, indent=2))
