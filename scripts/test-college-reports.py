import importlib.util
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

spec = importlib.util.spec_from_file_location("reports", Path(__file__).with_name("import-college-reports.py"))
reports = importlib.util.module_from_spec(spec)
spec.loader.exec_module(reports)


class Sheet:
    name = "CIE_ATTENDANCE"
    def __init__(self):
        self.values = [[""] * 6 for _ in range(12)]
        self.values[1][0] = "Fictional College"
        self.values[2][0] = "FINAL CIE & ATTENDANCE REPORT"
        self.values[3][0] = "B.E-TEST-Semester : 8 -SEC A"
        self.values[5] = ["SL. No.", "Student Name", "USN", "TEST101", "", ""]
        self.values[6] = ["", "", "", "CIE", "Attendance", "Eligible/not eligible "]
        self.values[7] = [1, "Fictional Student", "TEST001", 0, 79, "No"]
        self.values[9] = ["Sl.No", "Subject Code", "Subject Name", "Credit", "", ""]
        self.values[10] = [1, "TEST101", "Fictional Subject", 3, "", ""]
        self.values[11][0] = "Report Generated By: Test ON 27-09-2026"
        self.nrows, self.ncols = len(self.values), 6
    def cell_value(self, r, c): return self.values[r][c]
    def row_values(self, r): return self.values[r]


class Book:
    nsheets = 1
    def __init__(self, sheet): self.sheet = sheet
    def sheet_by_index(self, index): return self.sheet


class ReportTests(unittest.TestCase):
    def parse(self, sheet, identities=None):
        with tempfile.TemporaryDirectory() as directory:
            source = Path(directory) / "TEST.xls"; source.write_bytes(b"fictional workbook")
            with patch.object(reports.attendance, "read_verified", return_value=(Book(sheet), False, sheet.nrows * sheet.ncols)):
                return reports.parse_cie(source, identities if identities is not None else {})

    def test_legend_footer_zero_and_eligibility_remain_separate(self):
        result = self.parse(Sheet())
        self.assertEqual(result['summary']['studentRows'], 1)
        self.assertEqual(result['rows'][0]['cells'][0]['rawValue'], 0)
        self.assertEqual(result['rows'][0]['cells'][2]['rawValue'], 'No')
        self.assertEqual(result['rows'][0]['cells'][1]['sourceCell'], 'E8')
        self.assertEqual(result['source']['legend'][0]['credits'], 3)
        self.assertIsNone(result['source']['periodStart'])

    def test_repeat_import_reuses_identity(self):
        identities = {}; first = self.parse(Sheet(), identities); second = self.parse(Sheet(), identities)
        self.assertEqual(first['rows'][0]['studentId'], second['rows'][0]['studentId'])

    def test_dash_blank_and_unknown_tokens(self):
        self.assertEqual(reports.classify_cie('-', 'CIE'), 'source_status')
        self.assertEqual(reports.classify_cie('', 'CIE'), 'blank')
        for value, field in [('79', 'Attendance'), ('Yes', 'CIE'), (101, 'Attendance'), (True, 'CIE'), (1, 'Eligible/not eligible')]:
            with self.subTest(value=value, field=field), self.assertRaises(ValueError): reports.classify_cie(value, field)

    def test_duplicate_identity_and_unknown_footer_block_import(self):
        sheet = Sheet(); sheet.values[8] = [2, "Different Name", "TEST001", 1, 80, "Yes"]
        with self.assertRaises(ValueError): self.parse(sheet)
        sheet = Sheet(); sheet.values[11][0] = 'unexpected footer'
        with self.assertRaises(ValueError): self.parse(sheet)

    def test_missing_or_duplicate_legend_and_field_block_import(self):
        for kind in ['legend', 'field']:
            sheet = Sheet()
            if kind == 'legend': sheet.values[10][1] = 'OTHER101'
            else: sheet.values[6][4] = 'CIE'
            with self.subTest(kind=kind), self.assertRaises(ValueError): self.parse(sheet)

    def test_comparison_keeps_conflicts_and_unknown_statuses(self):
        cie = self.parse(Sheet())
        original = {'studentId': cie['rows'][0]['studentId'], 'semester': 8, 'section': 'Section A',
                    'courseKey': 'TEST101', 'kind': 'number', 'rawValue': 0, 'sourceId': 'a'*64, 'sourceCell': 'E8'}
        report = reports.compare_attendance({'observations': [original]}, cie)
        self.assertEqual(report['counts']['differentNumericSourceValues'], 1)
        self.assertEqual(report['differences'][0]['fullAttendanceValue'], 0)
        self.assertFalse(report['sourcesMerged'])
        original['kind'] = 'source_status'; original['rawValue'] = 'TNS'
        report = reports.compare_attendance({'observations': [original]}, cie)
        self.assertEqual(report['counts']['statusOrMissingNotComparable'], 1)
        original['semester'] = 6
        report = reports.compare_attendance({'observations': [original]}, cie)
        self.assertEqual(report['counts']['noMatchingCourse'], 1)


if __name__ == '__main__': unittest.main()
